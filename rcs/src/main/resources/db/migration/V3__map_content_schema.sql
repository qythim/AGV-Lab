-- V3__map_content_schema.sql
-- 建立 map document 版本表；JSON 的 GZIP 與 SHA-256 由 MapContentStore 處理。

CREATE TABLE rcs_map_content (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    map_code VARCHAR(64) NOT NULL REFERENCES rcs_map(map_code),
    version INTEGER NOT NULL CHECK (version > 0),
    content BYTEA NOT NULL,
    sha256 VARCHAR(64) NOT NULL,
    legacy_snapshot JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (map_code, version),
    UNIQUE (map_code, id)
);

ALTER TABLE rcs_map
    ADD COLUMN content_id BIGINT;

ALTER TABLE rcs_agv
    ADD COLUMN map_content_id BIGINT;

ALTER TABLE rcs_task
    ADD COLUMN map_content_id BIGINT;

ALTER TABLE rcs_lock_point
    ADD COLUMN map_content_id BIGINT;

-- 新模型不再以 rcs_point / rcs_map_object 作为 map document 的来源。
-- 这些表在全新数据库中没有业务数据，因此可安全移除。
DROP TABLE rcs_point CASCADE;
DROP TABLE rcs_map_object CASCADE;

ALTER TABLE rcs_map
    ADD CONSTRAINT fk_rcs_map_content
    FOREIGN KEY (map_code, content_id)
    REFERENCES rcs_map_content (map_code, id);

ALTER TABLE rcs_agv
    ADD CONSTRAINT fk_rcs_agv_map_content
    FOREIGN KEY (current_map_code, map_content_id)
    REFERENCES rcs_map_content (map_code, id);

ALTER TABLE rcs_task
    ADD CONSTRAINT fk_rcs_task_map_content
    FOREIGN KEY (map_code, map_content_id)
    REFERENCES rcs_map_content (map_code, id);

ALTER TABLE rcs_lock_point
    ADD CONSTRAINT fk_rcs_lock_point_map_content
    FOREIGN KEY (map_code, map_content_id)
    REFERENCES rcs_map_content (map_code, id);

ALTER TABLE rcs_task
    ALTER COLUMN map_content_id SET NOT NULL;

ALTER TABLE rcs_lock_point
    ALTER COLUMN map_content_id SET NOT NULL;

ALTER TABLE rcs_agv
    ADD CONSTRAINT chk_rcs_agv_map_content_pair
    CHECK ((current_map_code IS NULL) = (map_content_id IS NULL));
