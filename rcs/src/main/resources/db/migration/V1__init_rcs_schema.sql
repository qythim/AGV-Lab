-- V1__init_rcs_schema.sql
-- Khởi tạo 6 bảng chính của hệ thống RCS AGV

CREATE TABLE rcs_map (
    map_code VARCHAR(64) PRIMARY KEY,
    map_name VARCHAR(128) NOT NULL,
    version INTEGER NOT NULL DEFAULT 1 CHECK (version >= 1),
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    width NUMERIC(10,2) CHECK (width > 0),
    height NUMERIC(10,2) CHECK (height > 0),
    origin_x NUMERIC(10,2) NOT NULL DEFAULT 0,
    origin_y NUMERIC(10,2) NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uq_rcs_map_one_active ON rcs_map (is_active) WHERE is_active = TRUE;

CREATE TABLE rcs_point (
    point_code VARCHAR(64) NOT NULL,
    map_code VARCHAR(64) NOT NULL,
    x DOUBLE PRECISION NOT NULL,
    y DOUBLE PRECISION NOT NULL,
    z DOUBLE PRECISION NOT NULL DEFAULT 0,
    point_type VARCHAR(32) NOT NULL CHECK (point_type IN ('NORMAL','CHARGER','RACK','STATION')),
    heading_angle DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (heading_angle >= 0 AND heading_angle < 360),
    neighbors JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(neighbors) = 'array'),
    max_speed NUMERIC(4,2) NOT NULL DEFAULT 1.5 CHECK (max_speed > 0),
    is_disabled BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (map_code, point_code),
    FOREIGN KEY (map_code) REFERENCES rcs_map(map_code) ON DELETE CASCADE
);

CREATE TABLE rcs_agv (
    agv_code VARCHAR(64) PRIMARY KEY,
    agv_name VARCHAR(128),
    agv_type VARCHAR(32) NOT NULL CHECK (agv_type IN ('STANDARD','TELESCOPIC')),
    ip_address VARCHAR(45),
    port INTEGER CHECK (port BETWEEN 1 AND 65535),
    current_map_code VARCHAR(64),
    current_point VARCHAR(64),
    pos_x DOUBLE PRECISION,
    pos_y DOUBLE PRECISION,
    angle DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (angle >= 0 AND angle < 360),
    lift_height DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (lift_height >= 0),
    battery_level INTEGER NOT NULL DEFAULT 100 CHECK (battery_level BETWEEN 0 AND 100),
    status VARCHAR(32) NOT NULL DEFAULT 'IDLE' CHECK (status IN ('OFFLINE','IDLE','RUNNING','CHARGING','ERROR')),
    current_task_id VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (current_map_code) REFERENCES rcs_map(map_code),
    FOREIGN KEY (current_map_code, current_point) REFERENCES rcs_point(map_code, point_code),
    CHECK (current_point IS NULL OR current_map_code IS NOT NULL)
);

CREATE TABLE rcs_map_object (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    map_code VARCHAR(64) NOT NULL REFERENCES rcs_map(map_code) ON DELETE CASCADE,
    object_type VARCHAR(32) NOT NULL CHECK (object_type IN ('WALL','RACK','STATION','CHARGER','CONVEYOR')),
    pos_x DOUBLE PRECISION NOT NULL,
    pos_y DOUBLE PRECISION NOT NULL,
    pos_z DOUBLE PRECISION NOT NULL DEFAULT 0,
    rotation DOUBLE PRECISION NOT NULL DEFAULT 0,
    length DOUBLE PRECISION NOT NULL CHECK (length > 0),
    width DOUBLE PRECISION NOT NULL CHECK (width > 0),
    height DOUBLE PRECISION NOT NULL CHECK (height > 0),
    rack_levels INTEGER NOT NULL DEFAULT 1 CHECK (rack_levels >= 1),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE rcs_task (
    task_code VARCHAR(64) PRIMARY KEY,
    agv_code VARCHAR(64) REFERENCES rcs_agv(agv_code),
    map_code VARCHAR(64) NOT NULL REFERENCES rcs_map(map_code),
    start_point VARCHAR(64) NOT NULL,
    target_point VARCHAR(64) NOT NULL,
    target_level INTEGER NOT NULL DEFAULT 0 CHECK (target_level >= 0),
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','RUNNING','COMPLETED','FAILED')),
    finished_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (map_code, start_point) REFERENCES rcs_point(map_code, point_code),
    FOREIGN KEY (map_code, target_point) REFERENCES rcs_point(map_code, point_code)
);

CREATE TABLE rcs_lock_point (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    map_code VARCHAR(64) NOT NULL,
    point_code VARCHAR(64) NOT NULL,
    agv_code VARCHAR(64) NOT NULL REFERENCES rcs_agv(agv_code),
    task_id VARCHAR(64) REFERENCES rcs_task(task_code),
    lock_type VARCHAR(32) NOT NULL CHECK (lock_type IN ('OCCUPIED','RESERVED')),
    locked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expire_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_map_point UNIQUE (map_code, point_code),
    FOREIGN KEY (map_code, point_code) REFERENCES rcs_point(map_code, point_code),
    CHECK (expire_at > locked_at)
);

CREATE INDEX idx_rcs_point_map ON rcs_point(map_code);
CREATE INDEX idx_rcs_map_object_map ON rcs_map_object(map_code);
CREATE INDEX idx_rcs_task_status ON rcs_task(status);
CREATE INDEX idx_rcs_task_agv ON rcs_task(agv_code);
CREATE INDEX idx_rcs_lock_expire ON rcs_lock_point(expire_at);
