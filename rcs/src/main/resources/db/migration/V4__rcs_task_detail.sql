-- V4__rcs_task_detail.sql
-- 建立搬運任務明細表，記錄每個任務的各執行階段 (PICKUP / DELIVERY) 與起迄時間點

CREATE TABLE rcs_task_detail (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_code VARCHAR(64) NOT NULL REFERENCES rcs_task(task_code) ON DELETE CASCADE,
    step_seq INTEGER NOT NULL CHECK (step_seq >= 1),
    step_type VARCHAR(32) NOT NULL CHECK (step_type IN ('PICKUP', 'DELIVERY')),
    agv_code VARCHAR(64) NOT NULL REFERENCES rcs_agv(agv_code),
    from_point VARCHAR(64) NOT NULL,
    to_point VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'RUNNING', 'COMPLETED', 'FAILED')),
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_task_step_seq UNIQUE (task_code, step_seq)
);

CREATE INDEX idx_rcs_task_detail_task ON rcs_task_detail(task_code);

