package db.migration;

import org.flywaydb.core.api.migration.*;
import tools.jackson.databind.json.JsonMapper;
import java.sql.*;
import java.util.*;
import java.io.*;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.util.zip.GZIPOutputStream;

/** 將舊版資料完整封存並轉成有向地圖文件；整個遷移由 Flyway 交易保護。 */
public class V3__Map_documents extends BaseJavaMigration {
    @Override public void migrate(Context context) throws Exception {
        Connection db = context.getConnection();
        var mapper = JsonMapper.builder().build();
        try (Statement sql = db.createStatement()) {
            sql.execute("""
                CREATE TABLE rcs_map_content(
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    map_code VARCHAR(64) NOT NULL REFERENCES rcs_map(map_code),
                    version INTEGER NOT NULL CHECK(version > 0),
                    content BYTEA NOT NULL,
                    sha256 VARCHAR(64) NOT NULL,
                    legacy_snapshot JSONB,
                    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    UNIQUE(map_code,version), UNIQUE(map_code,id)
                )
                """);
            sql.execute("ALTER TABLE rcs_map ADD COLUMN content_id BIGINT");
            sql.execute("ALTER TABLE rcs_agv ADD COLUMN map_content_id BIGINT");
            sql.execute("ALTER TABLE rcs_task ADD COLUMN map_content_id BIGINT");
            sql.execute("ALTER TABLE rcs_lock_point ADD COLUMN map_content_id BIGINT");
        }
        List<String> maps = new ArrayList<>();
        try (Statement st = db.createStatement(); ResultSet rs = st.executeQuery("SELECT map_code FROM rcs_map ORDER BY map_code")) {
            while (rs.next()) maps.add(rs.getString(1));
        }
        for (String code : maps) {
            var doc = mapper.createObjectNode();
            var legacy = mapper.createObjectNode();
            int version;
            try (PreparedStatement st = db.prepareStatement("SELECT row_to_json(m)::text FROM rcs_map m WHERE map_code=?")) {
                st.setString(1, code);
                try (ResultSet rs = st.executeQuery()) {
                    rs.next();
                    var m = mapper.readTree(rs.getString(1));
                    legacy.set("map", m);
                    version = m.get("version").asInt();
                    var meta = doc.putObject("map");
                    meta.put("mapCode", code); meta.put("mapName", m.get("map_name").asString());
                    meta.put("version", version); meta.put("isActive", false);
                    meta.set("width", m.get("width")); meta.set("height", m.get("height"));
                    meta.set("originX", m.get("origin_x")); meta.set("originY", m.get("origin_y"));
                    meta.set("context", m.get("context"));
                }
            }
            var points = doc.putArray("pointList");
            var lines = doc.putArray("lineList");
            var oldPoints = legacy.putArray("points");
            Set<String> codes = new HashSet<>();
            try (PreparedStatement st = db.prepareStatement("SELECT row_to_json(p)::text FROM rcs_point p WHERE map_code=? ORDER BY point_code")) {
                st.setString(1, code);
                try (ResultSet rs = st.executeQuery()) {
                    while (rs.next()) {
                        var p = mapper.readTree(rs.getString(1)); oldPoints.add(p);
                        String pointCode = p.get("point_code").asString(); codes.add(pointCode);
                        var point = points.addObject();
                        point.put("pointCode", pointCode); point.put("pointName", pointCode);
                        point.set("x", p.get("x")); point.set("y", p.get("y")); point.set("pointType", p.get("point_type"));
                    }
                }
            }
            int lineIndex = 1;
            for (var p : oldPoints) {
                var neighbors = p.get("neighbors");
                if (neighbors.isString()) neighbors = mapper.readTree(neighbors.asString());
                if (!neighbors.isArray()) throw new IllegalStateException("舊地圖鄰接資料格式無效：" + code);
                Set<String> seen = new HashSet<>();
                for (var n : neighbors) {
                    String target = n.asString();
                    if (!codes.contains(target)) throw new IllegalStateException("舊地圖包含不存在的端點：" + code + "/" + target);
                    String source = p.get("point_code").asString();
                    if (!seen.add(target) || source.equals(target)) continue;
                    var line = lines.addObject();
                    line.put("lineCode", "L_" + String.format("%03d", lineIndex++));
                    line.put("startPointCode", source); line.put("endPointCode", target);
                    line.put("robotType", "ALL");
                    line.putArray("robotCarrierState").add("EMPTY").add("LOADED");
                    line.set("maxSpeed", p.get("max_speed")); line.put("stoppable", true);
                    line.putArray("allowedTravelModes").add("FORWARD").add("REVERSE");
                }
            }
            var objects = doc.putArray("objects");
            var oldObjects = legacy.putArray("objects");
            try (PreparedStatement st = db.prepareStatement("SELECT row_to_json(o)::text FROM rcs_map_object o WHERE map_code=? ORDER BY id")) {
                st.setString(1, code);
                try (ResultSet rs = st.executeQuery()) {
                    while (rs.next()) {
                        var old = mapper.readTree(rs.getString(1)); oldObjects.add(old);
                        var obj = objects.addObject();
                        String[] from = {"id","map_code","object_type","pos_x","pos_y","pos_z","rotation","length","width","height","rack_levels"};
                        String[] to = {"id","mapCode","objectType","posX","posY","posZ","rotation","length","width","height","rackLevels"};
                        for (int i=0; i<from.length; i++) obj.set(to[i], old.get(from[i]));
                    }
                }
            }
            byte[] raw = mapper.writeValueAsString(doc).getBytes(StandardCharsets.UTF_8);
            var buffer = new ByteArrayOutputStream();
            try (var gzip = new GZIPOutputStream(buffer)) { gzip.write(raw); }
            String hash = HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(raw));
            long id;
            try (PreparedStatement st = db.prepareStatement("""
                    INSERT INTO rcs_map_content(map_code,version,content,sha256,legacy_snapshot)
                    VALUES (?,?,?,?,?::jsonb) RETURNING id
                    """)) {
                st.setString(1, code); st.setInt(2, version); st.setBytes(3, buffer.toByteArray());
                st.setString(4, hash); st.setString(5, mapper.writeValueAsString(legacy));
                try (ResultSet rs=st.executeQuery()) { rs.next(); id=rs.getLong(1); }
            }
            String[] updates = {
                "UPDATE rcs_map SET content_id=? WHERE map_code=?",
                "UPDATE rcs_agv SET map_content_id=? WHERE current_map_code=?",
                "UPDATE rcs_task SET map_content_id=? WHERE map_code=?",
                "UPDATE rcs_lock_point SET map_content_id=? WHERE map_code=?"
            };
            for (String update : updates) try (PreparedStatement st=db.prepareStatement(update)) {
                st.setLong(1,id); st.setString(2,code); st.executeUpdate();
            }
        }
        // 只移除指向舊節點表的外鍵；保留車輛佔位與鎖定的唯一約束。
        List<String> constraints = new ArrayList<>();
        try (Statement st=db.createStatement(); ResultSet rs=st.executeQuery("""
                SELECT 'ALTER TABLE ' || conrelid::regclass || ' DROP CONSTRAINT ' || quote_ident(conname)
                FROM pg_constraint WHERE contype='f' AND confrelid='rcs_point'::regclass
                """)) {
            while(rs.next()) constraints.add(rs.getString(1));
        }
        try (Statement st=db.createStatement()) {
            for (String statement : constraints) st.execute(statement);
            st.execute("ALTER TABLE rcs_map ADD FOREIGN KEY(map_code,content_id) REFERENCES rcs_map_content(map_code,id)");
            st.execute("ALTER TABLE rcs_agv ADD FOREIGN KEY(current_map_code,map_content_id) REFERENCES rcs_map_content(map_code,id)");
            st.execute("ALTER TABLE rcs_task ADD FOREIGN KEY(map_code,map_content_id) REFERENCES rcs_map_content(map_code,id)");
            st.execute("ALTER TABLE rcs_lock_point ADD FOREIGN KEY(map_code,map_content_id) REFERENCES rcs_map_content(map_code,id)");
            st.execute("ALTER TABLE rcs_task ALTER COLUMN map_content_id SET NOT NULL");
            st.execute("ALTER TABLE rcs_lock_point ALTER COLUMN map_content_id SET NOT NULL");
            st.execute("ALTER TABLE rcs_agv ADD CHECK ((current_map_code IS NULL) = (map_content_id IS NULL))");
            st.execute("DROP TABLE rcs_point");
            st.execute("DROP TABLE rcs_map_object");
        }
    }
}
